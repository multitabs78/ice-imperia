-- =========================================================
-- Империя льда — личный кабинет
-- Миграция 006: вычистить персональные данные из журнала
-- ---------------------------------------------------------
-- Журнал хранил значения изменённых полей целиком, включая
-- имена, даты рождения и контакты. Из-за этого обезличивание
-- профиля ничего не давало: исходные данные оставались
-- в истории, откуда их никто не удалял.
--
-- Код это больше не пишет. Записи, сделанные раньше, чистим
-- здесь — по тем сущностям, где личные данные и хранились.
-- =========================================================

UPDATE audit_log
   SET before_json = NULL,
       after_json  = NULL
 WHERE entity IN ('athlete', 'parent', 'coach', 'user', 'admin')
   AND (before_json IS NOT NULL OR after_json IS NOT NULL);
